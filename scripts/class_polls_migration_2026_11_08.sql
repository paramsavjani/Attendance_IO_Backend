-- Class polls: schema for the polls feature. Run once against the production database BEFORE
-- deploying the backend that contains the poll entities. Everything runs in one transaction, so a
-- failure leaves the database untouched.
--
--   psql -v ON_ERROR_STOP=1 -f scripts/class_polls_migration_2026_11_08.sql
--
-- Definitions match what Hibernate (ddl-auto: update) generates for the entities, including
-- constraint names, so the app finds nothing to change on startup.
--
-- Nothing is ever deleted from these tables by the app:
--   poll.deleted_at       set when the creator deletes a poll (soft delete)
--   poll.creator_name     the creator's name when they asked, even for anonymous polls
--   poll_vote.removed_at  set when a vote is changed or withdrawn, so poll_vote is the full
--                         history of who voted for what and when; only rows with
--                         removed_at IS NULL count

BEGIN;

-- Push notification preference. The default lets it be added to the existing rows.
ALTER TABLE public.student
    ADD COLUMN poll_notifications_enabled boolean NOT NULL DEFAULT true;

CREATE TABLE public.poll (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    allow_multiple boolean NOT NULL,
    anonymous boolean NOT NULL,
    closed_at timestamp(6) with time zone,
    closes_at timestamp(6) with time zone NOT NULL,
    hidden boolean NOT NULL,
    question character varying(200) NOT NULL,
    creator_id bigint NOT NULL,
    subject_id bigint NOT NULL,
    creator_name character varying(100),
    deleted_at timestamp(6) with time zone
);

CREATE TABLE public.poll_option (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    "position" integer NOT NULL,
    text character varying(80) NOT NULL,
    poll_id bigint NOT NULL,
    CONSTRAINT uk_poll_option_position UNIQUE (poll_id, "position")
);

CREATE TABLE public.poll_vote (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    option_id bigint NOT NULL,
    poll_id bigint NOT NULL,
    student_id bigint NOT NULL,
    removed_at timestamp(6) with time zone
);

CREATE TABLE public.poll_report (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    reason character varying(20) NOT NULL,
    poll_id bigint NOT NULL,
    student_id bigint NOT NULL,
    CONSTRAINT uk_poll_report_poll_student UNIQUE (poll_id, student_id),
    CONSTRAINT poll_report_reason_check CHECK (reason IN ('SPAM', 'OFFENSIVE', 'MISLEADING', 'OTHER'))
);

CREATE INDEX idx_poll_creator_created ON public.poll (creator_id, created_at);
CREATE INDEX idx_poll_subject_created ON public.poll (subject_id, created_at);
CREATE INDEX idx_poll_vote_poll ON public.poll_vote (poll_id);
CREATE INDEX idx_poll_vote_student_poll ON public.poll_vote (student_id, poll_id);
-- One active vote per option per student; retired rows (history) are exempt.
CREATE UNIQUE INDEX uk_poll_vote_active ON public.poll_vote (option_id, student_id) WHERE removed_at IS NULL;

-- Foreign keys, named as Hibernate names them.
ALTER TABLE public.poll
    ADD CONSTRAINT fkgmccdyseg9y60pxg6ua03hb1j FOREIGN KEY (creator_id) REFERENCES public.student(id),
    ADD CONSTRAINT fknlyt7l4lo336a6fpjs6ml0ko1 FOREIGN KEY (subject_id) REFERENCES public.subjects(id);
ALTER TABLE public.poll_option
    ADD CONSTRAINT fk81hniv4vvdii51krao5f84hen FOREIGN KEY (poll_id) REFERENCES public.poll(id);
ALTER TABLE public.poll_vote
    ADD CONSTRAINT fka55jy2q182rsihqvlwd2qekw6 FOREIGN KEY (poll_id) REFERENCES public.poll(id),
    ADD CONSTRAINT fk4xh4rie3ubawv5fmtv17qona0 FOREIGN KEY (option_id) REFERENCES public.poll_option(id),
    ADD CONSTRAINT fk8sat32qfru9iivqv4i19hxhsj FOREIGN KEY (student_id) REFERENCES public.student(id);
ALTER TABLE public.poll_report
    ADD CONSTRAINT fk92hh3jqw2ml1emsk7llv6dp4r FOREIGN KEY (poll_id) REFERENCES public.poll(id),
    ADD CONSTRAINT fk2vnyvocwooy8d5ifq5whoxrqi FOREIGN KEY (student_id) REFERENCES public.student(id);

COMMIT;
